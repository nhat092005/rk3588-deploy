"""Write the 8x16 bitmap font of the box labels as a C++ header.

Each ASCII character from space to tilde is drawn once with DejaVu Sans
Mono (Bitstream Vera licence, which allows copying with the notice that
the header carries) in an 8x16 cell without anti-aliasing. The header
holds 16 bytes per character, one per row, the leftmost pixel in the
top bit. Prints the header to stdout and a preview of the sample text
to stderr.
Usage: make_label_font.py [font.ttf] > library/hardware/label/label_font.h
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

DEFAULT_FONT = Path("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf")
FIRST = 32
LAST = 126
WIDTH = 8
HEIGHT = 16
FONT_SIZE = 13
BASELINE = 12  # rows above the baseline; the descenders use the rest
THRESHOLD = 128
PREVIEW = "Helmet NoVest 87% #12 !"
COUNT = (LAST - FIRST + 1) * HEIGHT


def glyph_rows(font: ImageFont.FreeTypeFont, char: str) -> list[int]:
    """Return the 16 row bytes of one character."""
    cell = Image.new("L", (WIDTH, HEIGHT), 0)
    draw = ImageDraw.Draw(cell)
    draw.fontmode = "1"
    ascent, _ = font.getmetrics()
    draw.text((0, BASELINE - ascent), char, font=font, fill=255)
    rows = []
    for y in range(HEIGHT):
        bits = 0
        for x in range(WIDTH):
            bits = (bits << 1) | (cell.getpixel((x, y)) >= THRESHOLD)
        rows.append(bits)
    return rows


def preview(font_rows: dict[str, list[int]]) -> str:
    """Return the sample text as ASCII art."""
    lines = []
    for y in range(HEIGHT):
        line = ""
        for char in PREVIEW:
            row = font_rows[char][y]
            line += "".join(
                "#" if row & (1 << (WIDTH - 1 - x)) else "."
                for x in range(WIDTH)
            )
        lines.append(line)
    return "\n".join(lines)


HEADER = (
    "// Generated by tools/generate/make_label_font.py from DejaVu Sans Mono.",
    "// Do not edit.",
    "// Font: Copyright (c) 2003 Bitstream, Inc., Copyright (c) 2006",
    "// Tavmjong Bah. DejaVu changes are in the public domain. The Bitstream",
    "// Vera Fonts licence allows copying with this notice (not for sale",
    "// alone).",
    "#ifndef LABEL_FONT_H",
    "#define LABEL_FONT_H",
    "",
    "#include <array>",
    "#include <cstddef>",
    "#include <cstdint>",
    "",
    "/** @brief First and last character of the label font. */",
    f"constexpr int fontFirstChar{{{FIRST}}};",
    f"constexpr int fontLastChar{{{LAST}}};",
    "/** @brief Size of one glyph in pixels. */",
    f"constexpr int glyphWidth{{{WIDTH}}};",
    f"constexpr int glyphHeight{{{HEIGHT}}};",
    "",
    "/** @brief 16 row bytes per character, leftmost pixel in the top bit. */",
    f"constexpr std::array<std::uint8_t, {COUNT}> labelFont{{{{",
)


def main() -> int:
    """Print the header."""
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_FONT
    font = ImageFont.truetype(str(path), FONT_SIZE)
    rows = {
        chr(code): glyph_rows(font, chr(code))
        for code in range(FIRST, LAST + 1)
    }
    lines = list(HEADER)
    for code in range(FIRST, LAST + 1):
        values = ", ".join(f"0x{value:02X}" for value in rows[chr(code)])
        lines.append(f"        {values},  // 0x{code:02X}")
    lines += ["    }};", "", "#endif // LABEL_FONT_H"]
    print("\n".join(lines))
    print(preview(rows), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
