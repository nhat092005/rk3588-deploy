"""Write the C++ test data for the post-processing.

Reads the model_io fixtures of rk3588-common (three real INT8 board
outputs and the detections that ``model_io.postprocess_raw`` returns
for them) and prints ``test/postproc/postprocess_fixture.h`` to stdout.
Usage: make_postprocess_fixture.py common/tests > out.h
"""

import argparse
import importlib.util
import sys
from collections.abc import Mapping
from pathlib import Path
from types import ModuleType

import numpy as np

CHANNELS = 9  # 4 box channels + 5 classes
# Below this threshold many scores tie and numpy's unstable argsort
# decides the order of the ties, so the result is not reproducible.
MIN_CONF = 0.1


def load_cases(tests: Path) -> ModuleType:
    """Import common/tests/cases.py from its path."""
    spec = importlib.util.spec_from_file_location(
        "model_io_cases", tests / "cases.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def number(value: float) -> str:
    """Return a float32 literal that parses back to the same value."""
    return f"{float(np.float32(value)):.9e}F"


def emit_rows(dump: Mapping[str, np.ndarray]) -> list[str]:
    """Return the nonzero anchors of every image as C++ rows."""
    lines = []
    start = 0
    for count in dump["counts"]:
        for idx, vals in zip(
            dump["idx"][start : start + count],
            dump["vals"][start : start + count],
            strict=True,
        ):
            values = ", ".join(number(v) for v in vals)
            lines.append(f"    {{{int(idx)}, {{{values}}}}},")
        start += int(count)
    return lines


def main() -> int:
    """Print the header."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tests", type=Path, help="common/tests directory")
    tests = parser.parse_args().tests
    cases = load_cases(tests)
    dump = np.load(cases.DUMP)
    expected = np.load(cases.EXPECTED)
    out = [
        "// Generated by tools/generate/make_postprocess_fixture.py from the",
        "// rk3588-common model_io fixtures. Do not edit.",
        "#ifndef POSTPROCESS_FIXTURE_H",
        "#define POSTPROCESS_FIXTURE_H",
        "",
        "#include <array>",
        "#include <cstddef>",
        "",
        "namespace fixture {",
        f"inline constexpr std::size_t channelCount{{{CHANNELS}}};",
        "struct Mapping {",
        "    double gain;",
        "    int left;",
        "    int top;",
        "    int width;",
        "    int height;",
        "};",
        "struct Row {",
        "    int anchor;",
        "    std::array<float, channelCount> values;",
        "};",
        "struct Box {",
        "    float left;",
        "    float top;",
        "    float right;",
        "    float bottom;",
        "    float confidence;",
        "    int classId;",
        "};",
        "struct Case {",
        "    std::size_t image;",
        "    std::size_t mapping;",
        "    float confThreshold;",
        "    std::size_t firstBox;",
        "    std::size_t boxCount;",
        "};",
        "",
        f"inline constexpr std::array<Mapping, {len(cases.METAS)}>"
        " mappings{{",
    ]
    for gain, left, top, width, height in cases.METAS:
        out.append(f"    {{{gain!r}, {left}, {top}, {width}, {height}}},")
    out.append("}};")
    out.append("")
    counts = [int(c) for c in dump["counts"]]
    out.append(
        f"inline constexpr std::array<std::size_t, {len(counts)}> rowCounts{{"
    )
    out.append("    " + ", ".join(str(c) for c in counts))
    out.append("};")
    out.append("")
    rows = emit_rows(dump)
    out.append(f"inline constexpr std::array<Row, {len(rows)}> rows{{{{")
    out.extend(rows)
    out.append("}};")
    out.append("")

    boxes = []
    case_lines = []
    for image in range(len(counts)):
        for m in range(len(cases.METAS)):
            for c, conf in enumerate(cases.CONFS):
                if conf < MIN_CONF:
                    continue
                det = expected[f"dump{image}_m{m}_c{c}"]
                case_lines.append(
                    f"    {{{image}, {m}, {number(conf)}, "
                    f"{len(boxes)}, {len(det)}}},"
                )
                for x1, y1, x2, y2, score, cls in det:
                    boxes.append(
                        "    {"
                        + ", ".join(number(v) for v in (x1, y1, x2, y2, score))
                        + f", {int(cls)}}},"
                    )
    out.append(f"inline constexpr std::array<Box, {len(boxes)}> boxes{{{{")
    out.extend(boxes)
    out.append("}};")
    out.append("")
    out.append(
        f"inline constexpr std::array<Case, {len(case_lines)}> cases{{{{"
    )
    out.extend(case_lines)
    out.append("}};")
    out.append("} // namespace fixture")
    out.append("")
    out.append("#endif")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
