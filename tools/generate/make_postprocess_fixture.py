"""Write the C++ test data for the post-processing.

Reads a sparse INT8 board dump written by ``infer_dump.py`` of rk3588-ai
(the first images, real outputs of a model) and prints
``test/vision/postproc/postprocess_fixture.h`` to stdout, with the
detections that ``rk3588_common.model_io.postprocess_raw`` returns for
them at two letterbox mappings and the deployment confidence 0.25.
The class count, the anchor count and the input size come from the dump.
Usage: make_postprocess_fixture.py DUMP.npz [--images 3] > out.h
"""

import argparse
import sys
from collections.abc import Mapping
from pathlib import Path

import numpy as np

from rk3588_common import model_io

BOX_CHANNELS = 4
DEPLOY_CONF = 0.25
SCREEN_W, SCREEN_H = 1920, 1080

_nms_xyxy = model_io.nms_xyxy


def nms_ties_by_anchor(
    boxes: np.ndarray, scores: np.ndarray, iou_thres: float
) -> np.ndarray:
    """Run ``model_io.nms_xyxy`` with equal scores by rising anchor.

    An INT8 output has 256 score levels, so equal scores are common and
    ``scores.argsort()`` of numpy leaves their order open (it depends on
    the numpy build and the CPU). The C++ code takes the rising anchor
    index; the detections equal model_io's whenever no scores are equal.
    The candidates arrive in anchor order, so a stable sort gives that
    order. Distinct keys in that order make ``nms_xyxy`` use it.
    """
    rank = np.argsort(np.argsort(-scores, kind="stable"))
    return _nms_xyxy(boxes, -rank.astype(np.float32), iou_thres)


def number(value: float) -> str:
    """Return a float32 literal that parses back to the same value."""
    return f"{float(np.float32(value)):.9e}F"


def dense_outputs(
    dump: Mapping[str, np.ndarray], shape: tuple[int, int]
) -> list[np.ndarray]:
    """Rebuild the dense (1, channels, anchors) output per image."""
    preds, start = [], 0
    for count in dump["counts"]:
        pred = np.zeros((1, *shape), dtype=np.float32)
        pred[0][:, dump["idx"][start : start + count]] = dump["vals"][
            start : start + count
        ].T
        preds.append(pred)
        start += int(count)
    return preds


def emit_rows(dump: Mapping[str, np.ndarray]) -> list[str]:
    """Return the nonzero anchors of every image as C++ rows."""
    lines = []
    start = 0
    for count in dump["counts"]:
        for idx, vals in zip(
            dump["idx"][start : start + count],
            dump["vals"][start : start + count],
            strict=True,
        ):
            values = ", ".join(number(v) for v in vals)
            lines.append(f"    {{{int(idx)}, {{{values}}}}},")
        start += int(count)
    return lines


def main() -> int:
    """Print the header."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dump", type=Path, help="sparse board dump .npz")
    parser.add_argument("--images", type=int, default=3)
    args = parser.parse_args()
    full = np.load(args.dump)
    counts = [int(c) for c in full["counts"][: args.images]]
    used = sum(counts)
    dump = {
        "counts": counts,
        "idx": full["idx"][:used],
        "vals": full["vals"][:used],
    }
    channels, anchors = (int(v) for v in full["shape"])
    imgsz = {8400: 640, 18900: 960}[anchors]
    # a square frame, and a 16:9 frame letterboxed with padding on top
    gain = imgsz / SCREEN_W
    top = (imgsz - round(SCREEN_H * gain)) // 2
    metas = [
        (1.0, 0, 0, imgsz, imgsz),
        (gain, 0, top, SCREEN_W, SCREEN_H),
    ]
    out = [
        "// Generated by tools/generate/make_postprocess_fixture.py from a",
        "// sparse INT8 board dump and rk3588-common model_io. Do not edit.",
        "#ifndef POSTPROCESS_FIXTURE_H",
        "#define POSTPROCESS_FIXTURE_H",
        "",
        "#include <array>",
        "#include <cstddef>",
        "",
        "namespace fixture {",
        f"inline constexpr std::size_t channelCount{{{channels}}};",
        "inline constexpr std::size_t classCount"
        f"{{{channels - BOX_CHANNELS}}};",
        f"inline constexpr std::size_t anchorCount{{{anchors}}};",
        f"inline constexpr int modelSize{{{imgsz}}};",
        "struct Mapping {",
        "    double gain;",
        "    int left;",
        "    int top;",
        "    int width;",
        "    int height;",
        "};",
        "struct Row {",
        "    int anchor;",
        "    std::array<float, channelCount> values;",
        "};",
        "struct Box {",
        "    float left;",
        "    float top;",
        "    float right;",
        "    float bottom;",
        "    float confidence;",
        "    int classId;",
        "};",
        "struct Case {",
        "    std::size_t image;",
        "    std::size_t mapping;",
        "    float confThreshold;",
        "    std::size_t firstBox;",
        "    std::size_t boxCount;",
        "};",
        "",
        f"inline constexpr std::array<Mapping, {len(metas)}> mappings{{{{",
    ]
    for gain, left, top, width, height in metas:
        out.append(f"    {{{gain!r}, {left}, {top}, {width}, {height}}},")
    out.append("}};")
    out.append("")
    out.append(
        f"inline constexpr std::array<std::size_t, {len(counts)}> rowCounts{{"
    )
    out.append("    " + ", ".join(str(c) for c in counts))
    out.append("};")
    out.append("")
    rows = emit_rows(dump)
    out.append(f"inline constexpr std::array<Row, {len(rows)}> rows{{{{")
    out.extend(rows)
    out.append("}};")
    out.append("")

    model_io.nms_xyxy = nms_ties_by_anchor
    preds = dense_outputs(dump, (channels, anchors))
    boxes = []
    case_lines = []
    for image, pred in enumerate(preds):
        for m, meta in enumerate(metas):
            det = model_io.postprocess_raw(
                [pred], meta, True, conf_thres=DEPLOY_CONF, imgsz=imgsz
            )
            case_lines.append(
                f"    {{{image}, {m}, {number(DEPLOY_CONF)}, "
                f"{len(boxes)}, {len(det)}}},"
            )
            for x1, y1, x2, y2, score, cls in det:
                boxes.append(
                    "    {"
                    + ", ".join(number(v) for v in (x1, y1, x2, y2, score))
                    + f", {int(cls)}}},"
                )
    out.append(f"inline constexpr std::array<Box, {len(boxes)}> boxes{{{{")
    out.extend(boxes)
    out.append("}};")
    out.append("")
    out.append(
        f"inline constexpr std::array<Case, {len(case_lines)}> cases{{{{"
    )
    out.extend(case_lines)
    out.append("}};")
    out.append("} // namespace fixture")
    out.append("")
    out.append("#endif")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
